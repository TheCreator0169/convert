"""Writes shell_ext/exts.h (supported extensions and their type) and shell_ext/quick.h (quick targets per type)
from convert_win.formats (EXT_TYPE, QUICK, OUTPUTS).

Run from the repo root: .venv-win/Scripts/python.exe tools/gen_ext_header.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from convert_win.formats import EXT_TYPE, OUTPUTS, QUICK  # noqa: E402

OUT = ROOT / "shell_ext" / "exts.h"
QUICK_OUT = ROOT / "shell_ext" / "quick.h"

# Order of the QuickType enum and of the generated tables. Must match the C++ side.
TYPES = ("audio", "video", "image", "doc", "pdf")
ID_RE = re.compile(r"^[a-z0-9-]+$")
TEXT_RE = re.compile(r"^[\x20-\x7e]+$")  # printable ASCII


def _quick_entries(kind):
    """(id, label, ext) for each QUICK id of this type, in QUICK order. Video ids that are not video outputs are audio."""
    rows = []
    for fmt_id in QUICK[kind]:
        if kind == "video" and fmt_id not in OUTPUTS["video"]:
            fmt = OUTPUTS["audio"][fmt_id]
        else:
            fmt = OUTPUTS[kind][fmt_id]
        if not ID_RE.match(fmt_id):
            raise ValueError(f"quick id not ASCII-safe: {fmt_id!r}")
        if not TEXT_RE.match(fmt.label) or '"' in fmt.label or "\\" in fmt.label:
            raise ValueError(f"label not plain ASCII: {fmt.label!r}")
        if not ID_RE.match(fmt.ext):
            raise ValueError(f"ext not plain: {fmt.ext!r}")
        rows.append((fmt_id, fmt.label, fmt.ext))
    return rows


def build_quick() -> str:
    if set(QUICK) != set(TYPES):
        raise ValueError(f"QUICK must have exactly the types {TYPES}")
    lines = [
        "// generated, do not edit: written by tools/gen_ext_header.py from convert_win.formats.QUICK and OUTPUTS.",
        "#pragma once",
        "// Same order as the types in tools/gen_ext_header.py (TYPES).",
        "enum QuickType : unsigned char {",
        "    kQuickAudio,",
        "    kQuickVideo,",
        "    kQuickImage,",
        "    kQuickDoc,",
        "    kQuickPdf,",
        "};",
        "static const int kQuickTypeCount = 5;",
        "struct QuickFmt {",
        "    const wchar_t* id;     // --quick argument",
        "    const wchar_t* label;  // shown as 'Convert to <label>'",
        "    const wchar_t* ext;    // output extension without dot",
        "};",
    ]
    names = []
    for kind in TYPES:
        cap = kind.capitalize()
        rows = _quick_entries(kind)
        lines.append(f"static const QuickFmt kQuick{cap}Fmts[] = {{")
        lines += [f'    {{L"{i}", L"{lab}", L"{ext}"}},' for i, lab, ext in rows]
        lines.append("};")
        lines.append(f"static const size_t kQuick{cap}Count = {len(rows)};")
        names.append(f"kQuick{cap}")
    lines.append("static const QuickFmt* const kQuickLists[] = {" + ", ".join(f"{n}Fmts" for n in names) + "};")
    lines.append("static const size_t kQuickCounts[] = {" + ", ".join(f"{n}Count" for n in names) + "};")
    return "\n".join(lines) + "\n"


def build_exts() -> str:
    type_of = {f".{e.lower()}": t for e, t in EXT_TYPE.items()}
    exts = sorted(type_of)
    types = [type_of[e] for e in exts]
    lines = [
        "// Generated by tools/gen_ext_header.py from convert_win.formats.EXT_TYPE. Do not edit.",
        "#pragma once",
        '#include "quick.h"',
        "static const wchar_t* const kExts[] = {",
    ]
    lines += [f'    L"{e}",' for e in exts]
    lines += [
        "};",
        "// kExtTypes[i] is the QuickType of kExts[i].",
        "static const unsigned char kExtTypes[] = {",
    ]
    lines += [f"    kQuick{t.capitalize()}," for t in types]
    lines += [
        "};",
        f"static const size_t kExtCount = {len(exts)};",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    exts_text = build_exts()
    quick_text = build_quick()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(exts_text, encoding="utf-8", newline="\n")
    QUICK_OUT.write_text(quick_text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({exts_text.count(chr(10))} lines)")
    print(f"wrote {QUICK_OUT} ({quick_text.count(chr(10))} lines)")
